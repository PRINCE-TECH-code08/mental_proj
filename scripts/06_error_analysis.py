"""Phase 6: when does the model fail? Uses the single held-out test evaluation written by step 05."""
from _common import *
import numpy as np, pandas as pd
from scipy import stats
from mhp.metrics import reg_metrics
t = pd.read_csv(C.RESULTS / "test_predictions.csv", index_col="row_id")
for m in ("improved", "baseline"):
    t[f"res_{m}"] = t[f"pred_{m}"] - t.y_true
t["abs_res"] = t.res_improved.abs()
L = ["# Error Analysis (test set, n=%d)\n" % len(t), "_Auto-generated by `scripts/06_error_analysis.py`._\n"]
w = L.append
slope, icp, r, p, se = stats.linregress(t.y_true, t.res_improved)
w(f"## Systematic bias\n\n- Residual (pred - true) regressed on true score: slope **{slope:.3f}** (SE {se:.3f}). A negative slope means the model over-predicts low true scores and under-predicts high ones (regression toward the mean).\n- Mean signed error: {t.res_improved.mean():+.3f}; residual SD {t.res_improved.std():.3f}; max |error| {t.abs_res.max():.2f}.\n")
def binned(col, bins=None, q=None, labels=None):
    g = pd.qcut(t[col], q, duplicates="drop") if q else (t[col] if bins is None else pd.cut(t[col], bins))
    d = t.groupby(g, observed=True).apply(lambda x: pd.Series(dict(n=len(x), MAE=x.abs_res.mean(), bias=x.res_improved.mean(), MAE_baseline=x.res_baseline.abs().mean())))
    return d
tabs = {}
tabs["true score (quintiles)"] = binned("y_true", q=5)
tabs["sleep hours (quartiles)"] = binned("Sleep_Hours_Per_Night", q=4)
tabs["screen hours (quartiles)"] = binned("Avg_Daily_Usage_Hours", q=4)
tabs["stress level"] = t.groupby("Stress_Level").apply(lambda x: pd.Series(dict(n=len(x), MAE=x.abs_res.mean(), bias=x.res_improved.mean(), MAE_baseline=x.res_baseline.abs().mean()))).reindex(C.STRESS_ORDER)
for k, d in tabs.items():
    w(f"## Error by {k}\n\n" + d.round(3).to_markdown() + "\n")
worst = []
for k, d in tabs.items():
    i = d.MAE.idxmax(); worst.append((d.MAE.max(), k, str(i), int(d.loc[i, "n"])))
worst.sort(reverse=True)
w("## WHEN DOES THE MODEL FAIL?\n\n(All statements are computed above, on one test sample; differences between bins of ~50-400 rows carry sampling noise.)\n")
for m, k, i, n in worst:
    w(f"- Highest error within *{k}*: **{i}** (MAE {m:.3f}, n={n}).")
w(f"- Overall MAE {t.abs_res.mean():.3f}; 90th percentile |error| {t.abs_res.quantile(.9):.3f}; 99th percentile {t.abs_res.quantile(.99):.3f}.")
sp = {c: stats.spearmanr(t[c], t.abs_res)[0] for c in ["Age", "Avg_Daily_Usage_Hours", "Daily_Unlocks", "Study_Hours", "Physical_Activity_Hours", "Sleep_Hours_Per_Night", "y_true"]}
w("\nSpearman correlation of |error| with each numeric variable (heteroscedasticity check): " + ", ".join(f"{k}: {v:+.2f}" for k, v in sp.items()) + "\n")
w("## Twenty largest errors (improved model)\n\n" + t.sort_values("abs_res", ascending=False).head(20)[["y_true", "pred_improved", "pred_baseline", "Stress_Level", "Sleep_Hours_Per_Night", "Avg_Daily_Usage_Hours", "Academic_Level"]].round(2).to_markdown() + "\n")
w("## Interpretation limits\n\nErrors are computed against the dataset's own score. If that score is noisy or synthetic, part of the residual is irreducible; NOT ESTABLISHED how much.\n")
(C.REPORTS / "error_analysis.md").write_text("\n".join(L))
import matplotlib.pyplot as plt
fig, ax = plt.subplots(1, 2, figsize=(9, 4), sharex=True, sharey=True)
for a, m, c in zip(ax, ("baseline", "improved"), ("#C97C3B", "#21594A")):
    a.scatter(t.y_true, t[f"pred_{m}"], s=6, alpha=.35, color=c); a.plot([3.5, 9.5], [3.5, 9.5], "k--", lw=1); a.set_title(f"{m}: predicted vs actual"); a.set_xlabel("actual")
ax[0].set_ylabel("predicted"); fig.savefig(C.FIGURES / "predicted_vs_actual.png"); plt.close(fig)
fig, ax = plt.subplots(1, 2, figsize=(9, 3.6))
ax[0].scatter(t.pred_improved, t.res_improved, s=6, alpha=.35, color="#21594A"); ax[0].axhline(0, color="k", lw=1); ax[0].set_xlabel("predicted"); ax[0].set_ylabel("residual"); ax[0].set_title("Residuals vs predicted (improved)")
ax[1].scatter(t.y_true, t.res_improved, s=6, alpha=.35, color="#21594A"); ax[1].axhline(0, color="k", lw=1); ax[1].set_xlabel("actual"); ax[1].set_title("Residuals vs actual")
fig.savefig(C.FIGURES / "residuals.png"); plt.close(fig)
fig, ax = plt.subplots(figsize=(6, 3.6)); bins = np.linspace(-2, 2, 41)
ax.hist(t.res_baseline, bins, alpha=.55, label="baseline", color="#C97C3B"); ax.hist(t.res_improved, bins, alpha=.55, label="improved", color="#21594A"); ax.legend(); ax.set_xlabel("prediction error"); ax.set_title("Error distribution")
fig.savefig(C.FIGURES / "error_distribution.png"); plt.close(fig)
print("\n".join(L[2:4])); print("\n".join(L[-12:-6]))
