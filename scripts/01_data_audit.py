"""Phase 1: reproducible data-quality audit. Raw data is read-only. Writes reports/data_quality_report.md + figures."""
from _common import *
import numpy as np, pandas as pd, seaborn as sns
from scipy import stats

raw = D.load_raw()
log = {}
df = D.clean(raw, log)
num = raw.select_dtypes("number").columns.tolist()
cat = raw.select_dtypes(exclude="number").columns.tolist()
L = []
w = L.append
w("# Data Quality Report\n\n_Auto-generated by `scripts/01_data_audit.py`. Every number below is computed from the raw CSV._\n")
w(f"## 1. Shape and types\n\n- Rows: **{len(raw)}**, columns: **{raw.shape[1]}**\n- Numeric: {num}\n- Categorical: {cat}\n- Missing values (total): **{int(raw.isna().sum().sum())}**\n")
dups = raw[raw.duplicated(keep=False)]
w(f"## 2. Duplicates\n\n- Fully duplicated rows dropped by baseline cleaning: **{log['duplicates_dropped']}** ({len(dups)} rows involved in {len(dups)//2} duplicate pair(s)).\n- Because the dataset has no ID column and values are rounded to one decimal, a duplicate may be a genuine coincidence rather than a data error. NOT ESTABLISHED which.\n")
neg = raw[raw.Physical_Activity_Hours < 0]
w(f"## 3. Invalid / out-of-range values\n\n- `Physical_Activity_Hours < 0`: **{len(neg)}** rows (min {raw.Physical_Activity_Hours.min()}). The baseline clips these to 0. Clipping hides a data-entry problem rather than fixing it; we keep the same rule for comparability and flag it as a limitation.\n")
rng = raw[num].agg(["min", "max", "mean", "std"]).T.round(3)
w("### Numeric ranges (the model's **training domain**)\n\n" + rng.to_markdown() + "\n")
w(f"- **Age spans only {int(raw.Age.min())}-{int(raw.Age.max())}.** The baseline API accepts ages 10-100, i.e. it extrapolates far outside the training domain. The improved API flags out-of-range inputs.\n")
w("## 4. Target\n")
t = df[C.TARGET]
w(f"- `{C.TARGET}`: min {t.min()}, max {t.max()}, mean {t.mean():.3f}, sd {t.std():.3f}, skew {stats.skew(t):.3f}. Observed range is **{t.min()}-{t.max()}**, not the 0-10 the UI implies; the model cannot be validated for scores outside it.\n")
w("## 5. Categorical distributions (after cleaning)\n")
for c in ["Gender", "Academic_Level", "Purpose_Of_Use", "Stress_Level", "Most_Used_Platform"]:
    vc = df[c].value_counts()
    w(f"**{c}**: " + ", ".join(f"{k} = {v} ({v/len(df):.1%})" for k, v in vc.items()) + "\n")
vc = df.Country.value_counts()
w(f"**Country**: {df.Country.nunique()} distinct values; the literal value 'Other' covers {vc['Other']} rows ({vc['Other']/len(df):.1%}); {int((vc==1).sum())} countries occur exactly once. Baseline groups to the top-10 values (which includes 'Other') + 'Other'.\n")
w("## 6. Correlation with the target (Pearson, numeric features)\n")
cor = df[num].corr()[C.TARGET].drop(C.TARGET).sort_values()
w(cor.round(3).to_frame("r").to_markdown() + "\n")
w("Strong negative association with screen time and unlocks; strong positive with study hours, sleep, activity. These are **associations in one cross-sectional sample, not causal effects.**\n")
gm = df.groupby("Stress_Level")[C.TARGET].agg(["mean", "std", "count"]).reindex(C.STRESS_ORDER).round(3)
w("## 7. Leakage / target-proximity assessment\n\n" + gm.to_markdown() + "\n")
eta = 1 - (df.groupby("Stress_Level")[C.TARGET].var() * df.Stress_Level.value_counts()).sum() / (t.var() * len(df))
w(f"- No feature is a deterministic function of the target and no ID/time column exists, so **classic row-level leakage is not detected**.\n- However `Stress_Level` (self-reported perceived stress) explains about **{eta:.1%}** of target variance on its own (eta^2). Conceptually it is very close to the outcome being 'predicted'. Predicting a wellbeing score from perceived stress is close to circular; the ablation study (`results/ablation_results.csv`) quantifies reliance on it.\n")
w("## 8. Subgroup representation\n")
for c in ["Gender", "Academic_Level"]:
    w(f"- {c}: " + ", ".join(f"{k}: {v}" for k, v in df[c].value_counts().items()))
w("- Grouped_country needs the model's own bucketing; see `results/subgroup_performance.csv`. Several countries have <100 rows, so subgroup conclusions there are low-power.\n")
w("## 9. What is NOT established from the available data\n\n- **Provenance**: who collected the data, how the score was measured, and whether it is real survey data or synthetic/simulated. Nothing in the files documents this. Treat all results as results on *this* file.\n- Whether `Mental_Health_Score` is a validated instrument score.\n- Whether rows are independent (no student ID).\n")
(C.REPORTS / "data_quality_report.md").write_text("\n".join(L))

# ---- figures
fig, ax = plt.subplots(1, 2, figsize=(9, 3.4))
sns.histplot(t, kde=True, ax=ax[0], color="#21594A"); ax[0].set_title("Target distribution")
sns.boxplot(data=df, x="Stress_Level", y=C.TARGET, order=C.STRESS_ORDER, ax=ax[1], color="#9CC5B2"); ax[1].set_title("Score by stress level")
fig.savefig(C.FIGURES / "target_distribution.png"); plt.close(fig)
fig, ax = plt.subplots(figsize=(6.5, 5.2))
sns.heatmap(df[num].corr(), annot=True, fmt=".2f", cmap="RdBu_r", center=0, ax=ax, cbar=False)
ax.set_title("Correlation matrix (numeric)"); fig.savefig(C.FIGURES / "correlation_matrix.png"); plt.close(fig)
save_json(log, C.RESULTS / "cleaning_log.json")
print("\n".join(L[:12])); print("cleaning:", log)
